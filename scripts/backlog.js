// Generates docs/backlog.md from the real Jira export (docs/jira/SAT-export.csv).
// Usage: node scripts/backlog.js
const fs = require('fs');
const path = require('path');
const { loadIssues } = require('./jira-csv');

const root = path.join(__dirname, '..');
const issues = loadIssues(path.join(root, 'docs/jira/SAT-export.csv'));
const epics = issues.filter((i) => i.type === 'Epic').sort((a, b) => a.key.localeCompare(b.key));
const stories = issues
  .filter((i) => i.type === 'Story')
  .sort((a, b) => Number(a.key.split('-')[1]) - Number(b.key.split('-')[1]));

const sum = (list) => list.reduce((s, i) => s + (i.points || 0), 0);
const group = (list, fn) =>
  list.reduce((m, i) => {
    const k = fn(i) || '(none)';
    (m[k] = m[k] || []).push(i);
    return m;
  }, {});

const lines = [];
lines.push('# Product Backlog');
lines.push('');
lines.push(
  '> Generated by `node scripts/backlog.js` from `docs/jira/SAT-export.csv` (Jira export of project ' +
    'SAT, supplied 2026-11-14). Do not edit numbers by hand; re-run the script.'
);
lines.push('');
lines.push('## Epics');
lines.push('');
lines.push('| Key | Epic | Stories | Points |');
lines.push('|---|---|---|---|');
for (const e of epics) {
  const s = stories.filter((x) => x.epicKey === e.key);
  lines.push(`| ${e.key} | ${e.summary} | ${s.length} | ${sum(s)} |`);
}
lines.push('');
lines.push('## Stories');
lines.push('');
lines.push('| Key | Story | Epic | Sprint | Priority | Points | Assignee | Status |');
lines.push('|---|---|---|---|---|---|---|---|');
for (const s of stories) {
  lines.push(
    `| ${s.key} | ${s.summary} | ${s.epicKey} | ${s.sprint} | ${s.priority} | ${s.points} | ${s.assignee} | ${s.status} |`
  );
}
lines.push('');
lines.push('## Totals (reconciliation)');
lines.push('');
lines.push(`- Stories: **${stories.length}**, total points: **${sum(stories)}**`);
for (const [k, v] of Object.entries(group(stories, (i) => i.sprint)))
  lines.push(`- ${k}: ${v.length} stories, ${sum(v)} points`);
lines.push('');
lines.push('| Assignee | Stories | Points |');
lines.push('|---|---|---|');
for (const [k, v] of Object.entries(group(stories, (i) => i.assignee)))
  lines.push(`| ${k} | ${v.length} | ${sum(v)} |`);
lines.push('');
const oversized = stories.filter((s) => s.points > 5);
lines.push('## Data-quality notes from the export');
lines.push('');
lines.push(
  `- Stories above 5 points (should be split per Definition of Ready): ${
    oversized.map((s) => `${s.key} (${s.points})`).join(', ') || 'none'
  }.`
);
lines.push(
  `- All ${stories.filter((s) => s.priority === 'Medium').length} of ${stories.length} stories have ` +
    'priority "Medium" in Jira; priorities were not differentiated.'
);
lines.push(
  `- Story descriptions are empty in the export (${
    stories.filter((s) => !s.description.trim()).length
  } of ${stories.length}); acceptance criteria are kept in this repo (see below).`
);
lines.push(
  '- Epics were created on 21 Oct 2026, after the stories (12 Oct 2026), and remain "To Do".'
);
lines.push('');

const ac = fs.readFileSync(path.join(root, 'docs/acceptance-criteria.md'), 'utf8');
lines.push(ac.replace(/^# .*\n/, '## Acceptance criteria\n'));

fs.writeFileSync(path.join(root, 'docs/backlog.md'), lines.join('\n'));
console.log(
  `Wrote docs/backlog.md — ${stories.length} stories, ${sum(stories)} points, ${epics.length} epics`
);
