const tests = jest.testResults.flatMap((file) =>
  file.assertionResults.map((a) => ({
    file: path
      .relative(root, file.name)
      .replace(/^tests\//, '')
      .replace(/\.test\.js$/, ''),
    title: [...a.ancestorTitles, a.title].join(' › '),
    status: a.status,
  }))
);

const executions = newman ? newman.run.executions : [];
const postmanFor = (patterns) =>
  executions.filter((e) => {
    const folder = (e.item.name || '') + ' ' + (e.cursor ? '' : '');
    return patterns.some((p) => folder.includes(p));
  });

const lines = [];
lines.push('# Traceability: story → acceptance tests → result');
lines.push('');
lines.push(
  `> Generated by \`node scripts/traceability.js\` on ${new Date().toISOString().slice(0, 10)} from ` +
    '`reports/jest-results.json` and `reports/newman/report.json`. Re-run after the tests change.'
);
lines.push('');
lines.push(
  `Jest: ${jest.numPassedTests}/${jest.numTotalTests} passed in ${jest.numTotalTestSuites} suites. ` +
    (newman
      ? `Newman: ${newman.run.stats.requests.total} requests, ${
          newman.run.stats.assertions.total - newman.run.stats.assertions.failed
        }/${newman.run.stats.assertions.total} assertions passed.`
      : 'Newman: no report found.')
);
lines.push('');
lines.push('| Story | Jest tests | Jest result | Postman requests | Postman result |');
lines.push('|---|---|---|---|---|');

const details = [];
for (const [key, name, filters, pm] of MAP) {
  const matched = tests.filter((t) =>
    filters.some(([file, re]) => t.file.endsWith(file) && (!re || re.test(t.title)))
  );
  const passed = matched.filter((t) => t.status === 'passed').length;
  const reqs = postmanFor(pm);
  const pmAssertions = reqs.flatMap((e) => e.assertions || []);
  const pmFailed = pmAssertions.filter((a) => a.error).length;
  lines.push(
    `| ${key} ${name} | ${matched.length} | ${passed === matched.length ? '✅' : '❌'} ${passed}/${matched.length} | ${
      reqs.length
    } | ${reqs.length ? `${pmFailed ? '❌' : '✅'} ${pmAssertions.length - pmFailed}/${pmAssertions.length} assertions` : '—'} |`
  );
  details.push(`### ${key} — ${name}`);
  details.push('');
  for (const t of matched)
    details.push(`- ${t.status === 'passed' ? '✅' : '❌'} \`${t.file}\` — ${t.title}`);
  for (const e of reqs)
    details.push(
      `- ${(e.assertions || []).some((a) => a.error) ? '❌' : '✅'} Postman — ${e.item.name}`
    );
  details.push('');
}

lines.push('');
lines.push('## Test IDs per story');
lines.push('');
lines.push(...details);

const out = path.join(root, 'docs/testing/traceability.md');
fs.writeFileSync(out, lines.join('\n'));
console.log(`Wrote ${path.relative(root, out)}`);
